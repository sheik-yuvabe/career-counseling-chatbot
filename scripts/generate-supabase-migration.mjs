import { exporter } from "@dbml/core";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const repositoryRoot = process.cwd();
const inputPath = path.join(repositoryRoot, "docs", "data-model", "yuvanext-phase-a-mvp.dbml");
const outputDirectory = path.join(repositoryRoot, "supabase", "migrations");
const outputPath = path.join(outputDirectory, "20260727000100_phase_a_mvp.sql");

const dbml = await readFile(inputPath, "utf8");
let sql = exporter.export(dbml, "postgres");

// auth.users is shown in DBML only to visualize Supabase-owned relationships.
// Supabase manages the real table, so our migration must never recreate it.
sql = sql.replace(/CREATE TABLE "auth"\."users"\s*\([\s\S]*?\);\s*/m, "");
sql = sql.replace(/COMMENT ON (?:TABLE|COLUMN) "auth"\."users"(?:\."[^"]+")? IS [^;]*;\s*/g, "");
sql = sql.replace(/CREATE SCHEMA "[^"]+";\s*/g, "");

const header = `-- Generated from docs/data-model/yuvanext-phase-a-mvp.dbml.
-- Do not edit this file without updating the DBML and generator.
-- auth.users is Supabase-managed and intentionally not created here.

create extension if not exists pgcrypto;

create schema if not exists assessment;
create schema if not exists recommendation;
create schema if not exists knowledge;
create schema if not exists counselor;
create schema if not exists safety_private;
create schema if not exists operations;

`;

await mkdir(outputDirectory, { recursive: true });
await writeFile(outputPath, `${header}${sql.trim()}\n`, "utf8");
process.stdout.write(`Generated ${outputPath}\n`);
